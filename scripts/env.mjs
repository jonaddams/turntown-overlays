// Writes .env values the browser needs into src/app/env.ts (gitignored).
// Run via `pnpm start` / `pnpm build`, which load .env then .env.local (later wins).
import { writeFileSync } from 'node:fs';

const key = process.env.NUTRIENT_LICENSE_KEY ?? '';
writeFileSync(
  new URL('../src/app/env.ts', import.meta.url),
  `// Generated by scripts/env.mjs from .env. Do not edit or commit.\nexport const NUTRIENT_LICENSE_KEY = ${JSON.stringify(key)};\n`,
);
console.log(`env.ts written (license key ${key ? 'set' : 'empty: trial mode'})`);
